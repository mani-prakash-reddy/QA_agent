"""Jira Cloud connector (REST v2): site URL + e-mail + API token. Each test case becomes an issue of the
chosen type; plain Jira has no test-case object, so the steps live in the description."""

from typing import Any

import httpx

from app.qa.integrations.base import (
    CasePayload,
    Connector,
    IntegrationError,
    Pushed,
    label_safe,
    strip_numbering,
)

PRIORITY = {"P1": "Highest", "P2": "High", "P3": "Medium", "P4": "Low"}


class Jira(Connector):
    platform = "jira"

    def _auth(self) -> httpx.Auth:
        return httpx.BasicAuth(self.username, self._secret)

    def _headers(self) -> dict[str, str]:
        return {"Accept": "application/json", "Content-Type": "application/json"}

    def test(self) -> str:
        me = self.request("GET", f"{self.base_url}/rest/api/2/myself")
        return f"signed in as {me.get('displayName') or me.get('emailAddress') or 'this account'}"

    def options(self, kind: str, parent: str = "") -> list[dict[str, str]]:
        if kind == "projects":
            rows = self.request("GET", f"{self.base_url}/rest/api/2/project")
            return [
                {"id": r["key"], "name": f"{r['key']}: {r.get('name', '')}"}
                for r in rows
            ]
        if kind == "issue_types":
            proj = self.request("GET", f"{self.base_url}/rest/api/2/project/{parent}")
            return [
                {"id": t["name"], "name": t["name"]}
                for t in proj.get("issueTypes", [])
                if not t.get("subtask")
            ]
        raise IntegrationError(f"unknown option list '{kind}'")

    def destination_key(self, destination: dict[str, Any]) -> str:
        return f"{destination.get('project_key')}/{destination.get('issue_type') or 'Task'}"

    @staticmethod
    def _description(case: CasePayload) -> str:
        pre = "\n".join(f"* {p}" for p in case.preconditions) or "None"
        steps = "\n".join(f"# {strip_numbering(s)}" for s in case.steps)
        return (
            f"*Requirement:* {case.requirement}\n*Type:* {case.test_type}"
            f"{f'  *Role:* {case.role}' if case.role else ''}"
            f"\n\n*Preconditions*\n{pre}\n\n*Steps*\n{steps}\n\n"
            f"*Expected result* (_{case.basis.replace('_', ' ')}_)\n{case.expected}\n\n"
            f"_Generated by QA Agent as {case.tc_key}._"
        )

    def _fields(self, case: CasePayload, with_priority: bool) -> dict[str, Any]:
        labels = ["qa-agent", label_safe(case.test_type), label_safe(case.requirement)]
        fields: dict[str, Any] = {
            "summary": f"[{case.tc_key}] {case.title}"[:250],
            "description": self._description(case),
            "labels": [x for x in labels if x],
        }
        if with_priority:
            fields["priority"] = {"name": PRIORITY.get(case.priority, "Medium")}
        return fields

    def create(self, destination: dict[str, Any], case: CasePayload) -> Pushed:
        base = {
            "project": {"key": destination["project_key"]},
            "issuetype": {"name": destination.get("issue_type") or "Task"},
        }
        try:
            data = self.request(
                "POST",
                f"{self.base_url}/rest/api/2/issue",
                json={"fields": {**base, **self._fields(case, True)}},
            )
        except IntegrationError as exc:
            if "priority" not in str(exc).lower():
                raise  # the project's screen has no priority field: send without it
            data = self.request(
                "POST",
                f"{self.base_url}/rest/api/2/issue",
                json={"fields": {**base, **self._fields(case, False)}},
            )
        key = str(data["key"])
        return Pushed(key, f"{self.base_url}/browse/{key}")

    def update(
        self, destination: dict[str, Any], external_id: str, case: CasePayload
    ) -> Pushed:
        try:
            self.request(
                "PUT",
                f"{self.base_url}/rest/api/2/issue/{external_id}",
                json={"fields": self._fields(case, True)},
            )
        except IntegrationError as exc:
            if "priority" not in str(exc).lower():
                raise
            self.request(
                "PUT",
                f"{self.base_url}/rest/api/2/issue/{external_id}",
                json={"fields": self._fields(case, False)},
            )
        return Pushed(external_id, f"{self.base_url}/browse/{external_id}")
