"""A STAND-IN for TestRail's API (not TestRail): enough of API v2 to try the integration end to end without an
account. Login qa@demo.test with the API key mock-key. Data lives in memory and is visible at /_state."""

import base64

from fastapi import FastAPI, HTTPException, Request

app = FastAPI(title="Mock TestRail")
CASES: dict[int, dict] = {}


def check(request: Request) -> None:
    h = request.headers.get("authorization", "")
    ok = h.startswith("Basic ") and base64.b64decode(h[6:]).decode() == "qa@demo.test:mock-key"
    if not ok:
        raise HTTPException(401, "Authentication failed")


@app.get("/index.php")
async def api(request: Request) -> object:
    check(request)
    ep = request.url.query.split("&")[0].removeprefix("/api/v2/")
    if ep == "get_projects":
        return {"offset": 0, "limit": 250, "size": 1, "projects": [{"id": 1, "name": "Demo project"}]}
    if ep.startswith("get_suites/"):
        return [{"id": 10, "name": "Master suite"}]
    if ep.startswith("get_sections/"):
        return {"sections": [{"id": 100, "name": "Generated by QA Agent"}, {"id": 101, "name": "Smoke"}]}
    raise HTTPException(404, "unknown endpoint")


@app.post("/index.php")
async def write(request: Request) -> object:
    check(request)
    ep = request.url.query.split("&")[0].removeprefix("/api/v2/")
    body = await request.json()
    if "custom_steps_separated" not in body:
        raise HTTPException(400, "Field :custom_steps_separated is missing")
    if ep.startswith("add_case/"):
        cid = 5000 + len(CASES) + 1
        CASES[cid] = {**body, "id": cid, "section_id": int(ep.split("/")[1])}
        return CASES[cid]
    if ep.startswith("update_case/"):
        cid = int(ep.split("/")[1])
        CASES[cid].update(body)
        return CASES[cid]
    raise HTTPException(404, "unknown endpoint")


@app.get("/_state")
def state() -> dict:
    return {"cases": list(CASES.values())}
